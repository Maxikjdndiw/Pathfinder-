// After vite build: takes the mentor page out of the public files (dist/) and hands it to the
// function netlify/functions/mentor-seite.mts, which serves it only at /m/<MENTOR_PFAD>.
// So /mentor and /mentor.html simply do not exist on the live site.
import { existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs';

const page = new URL('../dist/mentor.html', import.meta.url);
if (!existsSync(page)) throw new Error('dist/mentor.html not found: run vite build first');
const html = readFileSync(page, 'utf8');
writeFileSync(
  new URL('../netlify/functions/_shared/mentor-page.generated.ts', import.meta.url),
  `// GENERATED by scripts/hide-mentor.mjs after the build. Do not edit by hand.\nexport const MENTOR_HTML = ${JSON.stringify(html)};\n`,
);
rmSync(page);
console.log('mentor page: removed from dist/, served by the mentor-seite function only');
